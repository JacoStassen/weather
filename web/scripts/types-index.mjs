// Rebuilds src/types/index.ts from the ts-rs output in src/types/generated.
import { readdirSync, writeFileSync } from 'node:fs'

const dir = new URL('../src/types/', import.meta.url)
const names = readdirSync(new URL('generated/', dir))
  .filter((f) => f.endsWith('.ts'))
  .map((f) => f.slice(0, -3))
  .sort()
const body = names.map((n) => `export type { ${n} } from './generated/${n}'`).join('\n')
writeFileSync(new URL('index.ts', dir), `// Generated by scripts/types-index.mjs. Do not edit.\n${body}\n`)
console.log(`types/index.ts: ${names.length} types`)
